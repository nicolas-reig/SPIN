export function date(value, exact = false) {
    const parts = Object.fromEntries(new Intl.DateTimeFormat(language === 'de' ? 'de-DE' : 'en-GB', {
        day: '2-digit',
        month: '2-digit',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
        hourCycle: 'h23',
        ...(exact ? { second: '2-digit' } : {})
    }).formatToParts(new Date(value)).map(part => [part.type, part.value]));
    return `${Number(parts.day)}/${Number(parts.month)}/${parts.year}, ${parts.hour}:${parts.minute}${exact ? ':' + parts.second : ''}`;
}
