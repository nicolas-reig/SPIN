let language = 'de';
try {
    language = localStorage.getItem('hub-language') || 'de';
} catch {}
if (!dictionary[language]) language = 'de';
export const lang = () => language;
export const t = key => dictionary[language][key] ?? key;
export function setLanguage(value) {
    language = value;
    document.documentElement.lang = value;
    try {
        localStorage.setItem('hub-language', value);
    } catch {}
}
export function date(value, exact = false) {
    return new Intl.DateTimeFormat(language === 'de' ? 'de-DE' : 'en-GB', exact ? {
        dateStyle: 'full',
        timeStyle: 'short'
    } : {
        day: '2-digit',
        month: 'short',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit'
    }).format(new Date(value));
}
